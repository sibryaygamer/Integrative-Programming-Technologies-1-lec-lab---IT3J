<?php
$time = "Morning";

switch ($time){
    case "Dawn":
        echo "It is Dawn";
        break;

    case "Morning":
        echo "It is Morning";
        break;
    
    case "Afternoon":
        echo "It is Afternoon";
        break;
    
    case "Evening":
        echo "It is Evening";
        break;

    case "Midnight":
        echo "It is Midnight";
        break;
}

?>
